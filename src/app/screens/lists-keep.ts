// Отбор списка живёт вне показа экрана: возврат с карточки
// собирает экран заново и сбрасывал закладку, порядок и слово поиска.
import { ref } from 'vue'

/** Порядки показа списка. */
export type SortName = 'updated' | 'score' | 'rating' | 'nameUp' | 'nameDown'

/**
 * Вид показа: компактные строки и строки с миниатюрой.
 * Лежит рядом с закладкой и порядком, а не в настройках: это выбор
 * на сейчас, который меняют по ходу чтения списка.
 *
 * Крупные постеры (`tiles`) убраны. На телевизоре они показывали
 * по шесть штук на экран, и список из сотни записей приходилось
 * листать пультом минутами; обе оставшиеся строки вмещают по
 * десятку с лишним записей и при этом не теряют ни постера, ни
 * подписей — разница между ними только в размере картинки.
 *
 * По умолчанию строки с миниатюрой: постер в них виден, а по списку
 * узнают глазами, и без картинки строка читается хуже, чем с ней.
 */
export type ViewName = 'slim' | 'wide'

export const keptStatus = ref<string>('CURRENT')

export const keptSort = ref<SortName>('updated')

export const keptView = ref<ViewName>('wide')

export const keptWord = ref('')
