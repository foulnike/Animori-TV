// Геометрия сакуры: лепесток, пять поворотов, два разворота — подложка кнопки и метка рядом с текстом.
// Путь один на два контекста: две копии разошлись бы при первой правке, а это расхождение в самом знаке.
// Числа — в шапке SakuraBloom.vue: полуширина 0.7038 для кнопки, 0.52 для метки (узнаётся с 12 px).

/** Лепесток знака: остриём вверх, надрез в точке (16, 7). */
export const SAKURA_PETAL =
  'M16 17.1 C12.1 16.6 9.3 13.2 9.6 9.8 C9.8 6.5 12.9 4.5 16 7 ' +
  'C19.1 4.5 22.2 6.5 22.4 9.8 C22.7 13.2 19.9 16.6 16 17.1 Z'

/** Пять поворотов по 72 градуса — ровно как в маске знака. */
export const SAKURA_TURNS: ReadonlyArray<number> = [0, 72, 144, 216, 288]

// 1.7467 выводит радиус лепестка на 18 единиц в квадрате 32: размер знака, одинаков для обоих вариантов.
// 1.2291 — полуширина 0.7038, лепестки сходятся в точку (кнопка); 0.9075 — 0.52, с прорезями (метка).
// translate нужен, чтобы scale шёл от центра квадрата.
export function sakuraTurn(turn: number): string {
  return `rotate(${turn} 16 16) translate(16 16) scale(1.2291 1.7467) translate(-16 -16)`
}

/** Разворот для метки: сжатие другое (0.52 против 0.7038) — на 15 px плотные лепестки читаются кругом, узкие дают сакуру. */
export function sakuraTurnMark(turn: number): string {
  return `rotate(${turn} 16 16) translate(16 16) scale(0.9075 1.7467) translate(-16 -16)`
}
