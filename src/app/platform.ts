// Пункт: признак слабой платформы.
//
// Раскладка AniMori рисовалась под настольный компьютер и щедро пользует
// размытие подложки — стеклянные панели, аврора под окном, крупные пятна
// на главном экране. На телевизоре это стоит около ста миллисекунд на кадр
// не потому, что слаб видеочип (он укладывается в 10 мс), а потому что
// каждый кадр приходится заново снимать подложку под каждым стеклом.
//
// Отдельного «телевизионного» режима здесь нет: отличать телевизор от
// приставки и от телефона смысла не имеет, размытие не по карману ни одному
// из них. Признак один — Android.
//
// Что именно глушится, расписано в theme.css возле правил `.am-lite`.

const LITE = 'am-lite'

let weak = false

/// Слабая ли платформа. Верно с момента вызова markPlatform().
export function isWeakPlatform(): boolean {
  return weak
}

/**
 * Есть ли куда уводить наружу — то есть есть ли браузер.
 *
 * На телевизоре его нет, и `shell.openExternal` либо молча ничего не
 * делает, либо уводит в приложение, которого нет вовсе. Кнопка, которая
 * никуда не ведёт, хуже её отсутствия: человек жмёт, ничего не случается,
 * и непонятно, сломалось ли. Поэтому всё наружу на слабой платформе
 * не рисуется, а не просто перестаёт работать.
 */
export function canOpenOutside(): boolean {
  return !weak
}

/**
 * Отмечает корень, если платформа слабая.
 *
 * Звать до createApp(): класс должен уже стоять на <html> к первой
 * отрисовке, иначе человек увидит сначала дорогую раскладку и только
 * потом её упрощение.
 */
export function markPlatform(): void {
  const ua = typeof navigator === 'undefined' ? '' : navigator.userAgent || ''
  weak = /Android/i.test(ua)
  if (weak) document.documentElement.classList.add(LITE)
}
